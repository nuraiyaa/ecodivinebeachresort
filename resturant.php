<!-- ==========================================
     LIGHTBOX JAVASCRIPT LOGIC
     ========================================== -->
<script>
  // Interior Gallery Data passed to JS
  const diningGalleryItems = <?php echo json_encode($interior); ?>;
  let currentGalleryIndex = 0;
  let diningModalInstance = null;

  function openDiningLightbox(index) {
    currentGalleryIndex = index;
    updateLightboxContent();

    const modalEl = document.getElementById('diningLightboxModal');
    if (!diningModalInstance && typeof bootstrap !== 'undefined') {
      diningModalInstance = new bootstrap.Modal(modalEl);
    }
    if (diningModalInstance) {
      diningModalInstance.show();
    }
  }

  function updateLightboxContent() {
    const item = diningGalleryItems[currentGalleryIndex];
    if (!item) return;

    const imgEl = document.getElementById('lightboxImg');
    const titleEl = document.getElementById('lightboxTitle');
    const tagEl = document.getElementById('lightboxTag');
    const descEl = document.getElementById('lightboxDesc');
    const counterEl = document.getElementById('lightboxCounter');

    imgEl.style.opacity = '0.3';
    setTimeout(() => {
      imgEl.src = 'assets/img/resturant/' + item.img;
      imgEl.alt = item.title;
      imgEl.style.opacity = '1';
    }, 150);

    titleEl.textContent = item.title_bn;
    tagEl.textContent = item.tag;
    descEl.textContent = item.desc;
    counterEl.textContent = (currentGalleryIndex + 1) + ' / ' + diningGalleryItems.length;
  }

  document.addEventListener('DOMContentLoaded', function () {
    const prevBtn = document.getElementById('lightboxPrevBtn');
    const nextBtn = document.getElementById('lightboxNextBtn');

    if (prevBtn) {
      prevBtn.addEventListener('click', function (e) {
        e.stopPropagation();
        currentGalleryIndex = (currentGalleryIndex - 1 + diningGalleryItems.length) % diningGalleryItems.length;
        updateLightboxContent();
      });
    }

    if (nextBtn) {
      nextBtn.addEventListener('click', function (e) {
        e.stopPropagation();
        currentGalleryIndex = (currentGalleryIndex + 1) % diningGalleryItems.length;
        updateLightboxContent();
      });
    }

    // Keyboard navigation (Arrow keys & Esc)
    document.addEventListener('keydown', function (e) {
      const modalEl = document.getElementById('diningLightboxModal');
      if (modalEl && modalEl.classList.contains('show')) {
        if (e.key === 'ArrowLeft') {
          currentGalleryIndex = (currentGalleryIndex - 1 + diningGalleryItems.length) % diningGalleryItems.length;
          updateLightboxContent();
        } else if (e.key === 'ArrowRight') {
          currentGalleryIndex = (currentGalleryIndex + 1) % diningGalleryItems.length;
          updateLightboxContent();
        }
      }
    });
  });
</script>

